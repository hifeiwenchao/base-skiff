TRANSLATIONS = {
    "zh": {key: pair[0] for key, pair in _STRINGS.items()},
    "en": {key: pair[1] for key, pair in _STRINGS.items()},
}


class Translator:
    """Translate UI keys; unknown keys stay visible during development."""

    def __init__(self, language: str = "zh") -> None:
        self.set_language(language)

    @property
    def language(self) -> str:
        return self._language

    def set_language(self, language: str) -> None:
        self._language = "zh" if str(language).lower().startswith("zh") else "en"

    def tr(self, key: str, **kwargs: object) -> str:
        template = TRANSLATIONS[self._language].get(key, TRANSLATIONS["en"].get(key, key))
        return template.format(**kwargs) if kwargs else template
